//Operadores Comparación 

let x =  5;//asignación

//Operador == Comparar 
console.log(x == 6);//false por que estoy preguntando si 5=6 y eso es falso
console.log(x == 5);//true por que estoy preguntando si 5=5 y es verdadero lo unico es que lo da en ingles

//Operador ===  Compara el valor y el tipo de dato
console.log(x === 5);//true por que compara que el numero sea igual y el tipo de dato
console.log(x === 5)

//Operador != Diferente 
console.log(x != 8)//true por que 5 es diferente a 8 
console.log(x != 5)//False por que 5 no es diferente de 5

//Operador !== Diferente el valor y tipo de dato
console.log(x !== 5)// false por que 5 y 5 son igual y los dos son numeros 
console.log(x == "5")//true por que aunque 5 es igual a 5 el uno esta en numero y el otro en texto

//Operador >Mayor que 
console.log(x > 10)//False por que esta preguntando si el 5 es mayor a 10
console.log(x > 2)// True por que 5 es mayor que 2

//Operador < Menor que
console.log(x < 10)//True por que esta preguntando si 5 es menor que 10
console.log(x < 2)//False por que 5 es menor que 2

//Operador >= Mayor o Igual que (si se cumple una de las dos ya es un true)
console.log(x >= 4)//True por que esta preguntando si 5 es mayor o igual que 4
console.log(x >= 5)//True por que aunque no es mayor si es igual
console.log(x >= 6)//False por que no es ni igual ni igual  

//Operador <= Menor o Igual que (Si se cumple una de las dos se cumpla)
console.log(x <= 4)//false por que no cumple ninguna de las dos 
console.log(x <= 5)//True por que es igual al 5 
console.log(x <= 6)// True por que es menor 

